#include "config/gpu_catalogue.hpp"

#include <cuda_runtime_api.h>

#include <cctype>
#include <cstdint>
#include <cstdio>
#include <cstring>
#include <fstream>
#include <iterator>
#include <sstream>
#include <string>
#include <string_view>

namespace {
struct Entry {
    const char*  type;
    const char*  name;
    unsigned     arch;
};
#define MK_ENTRY(T) Entry{#T, mk::T::name, mk::T::cuda_arch},
constexpr Entry catalogue[] = {MK_GPU_CATALOGUE(MK_ENTRY)};
#undef MK_ENTRY

// The only GPU measured: what an unknown card gets until someone measures it.
constexpr unsigned unmeasured_blocks_per_sm = 2;

std::string catalogue_types() {
    std::string out;
    for (const Entry& e : catalogue) {
        out += out.empty() ? "" : ", ";
        out += e.type;
    }
    return out;
}

// Stderr is the whole of CMake's error: one message that says what to do.
int fail(const std::string& what) {
    std::fprintf(stderr,
                 "%s\nBuild for a GPU that is not in this machine with -DMK_GPU=<type>, one of: %s\n",
                 what.c_str(), catalogue_types().c_str());
    return 1;
}

// The header is written only when it changes: a configure must not rebuild everything.
bool write_if_changed(const std::string& path, const std::string& text) {
    std::ifstream in(path, std::ios::binary);
    const std::string old{std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>()};
    if (in.is_open() && old == text) {
        return true;
    }
    std::ofstream out(path, std::ios::binary | std::ios::trunc);
    out << text;
    return static_cast<bool>(out);
}

// The name goes into a C++ string literal and a CMake list.
bool plain(std::string_view s) {
    for (const char c : s) {
        if (!std::isalnum(static_cast<unsigned char>(c)) && std::strchr(" .-_+()", c) == nullptr) {
            return false;
        }
    }
    return !s.empty();
}

std::string num(std::uint64_t v) { return std::to_string(v) + "u"; }

// A catalogue type's number that the driver contradicts stops the build, with both numbers.
std::string check(const char* type, const char* field, const char* op, std::uint64_t reported,
                  const char* claim) {
    return std::string("static_assert(") + type + "::" + field + " " + op + " " + num(reported) +
           ", \"gpu_catalogue.hpp's " + type + "::" + field + " " + claim + " the " +
           std::to_string(reported) + " this machine's GPU reports\");\n";
}
} // namespace

// gpu_probe <detect|detected|Type> <out.hpp>: CMake runs it at every configure and compiles
// the header's types into the build. Prints "<type> <cuda arch> <description>" on one line.
//   detect    asks the CUDA runtime about device 0 (what the engine uses, under
//             CUDA_VISIBLE_DEVICES): the catalogue's type for a known card, a generated
//             DetectedGpu for another.
//   detected  the generated type, also for a known card.
//   Type      a catalogue type, for a GPU that is not here: no device is asked.
int main(int argc, char** argv) {
    if (argc != 3) {
        std::fprintf(stderr, "usage: gpu_probe <detect|detected|Type> <out.hpp>\n");
        return 2;
    }
    const std::string_view mode = argv[1];
    const std::string      out  = argv[2];
    std::string header =
        "// Generated by gpu_probe at configure time. Do not edit.\n#pragma once\n"
        "#include \"config/gpu_catalogue.hpp\"\nnamespace mk {\n";

    if (mode != "detect" && mode != "detected") {
        for (const Entry& e : catalogue) {
            if (mode == e.type) {
                header += std::string("// MK_GPU=") + e.type + " names a GPU, so no device was asked.\n}\n";
                if (!write_if_changed(out, header)) {
                    return fail("cannot write " + out);
                }
                std::printf("%s %u %s, named by MK_GPU\n", e.type, e.arch, e.name);
                return 0;
            }
        }
        return fail("MK_GPU=" + std::string(mode) +
                    " is not a GPU this build knows, nor detect or detected: add its type to "
                    "src/config/gpu_catalogue.hpp.");
    }

    int        devices = 0;
    cudaError_t e      = cudaGetDeviceCount(&devices);
    cudaDeviceProp p{};
    if (e == cudaSuccess && devices > 0) {
        e = cudaGetDeviceProperties(&p, 0);
    }
    if (e == cudaSuccess && devices > 0) {
        e = cudaFree(nullptr); // makes the context: a device the engine could not use fails here
    }
    if (e != cudaSuccess || devices == 0) {
        return fail(std::string("MK_GPU=") + std::string(mode) + ": no usable CUDA device (" +
                    (e != cudaSuccess ? cudaGetErrorString(e) : "the runtime reports 0 devices") +
                    ").");
    }
    const std::string driver_name = p.name;
    if (!plain(driver_name)) {
        return fail("the device's name '" + driver_name + "' has a character this probe does not copy.");
    }
    const unsigned arch = static_cast<unsigned>(p.major * 10 + p.minor);
    const std::uint64_t shared_per_sm = p.sharedMemPerMultiprocessor;
    const std::uint64_t reserved      = p.reservedSharedMemPerBlock;
    const std::string facts = driver_name + ", " + std::to_string(p.multiProcessorCount) +
                              " SMs, sm_" + std::to_string(arch) + ", " +
                              std::to_string(p.totalGlobalMem >> 20) + " MiB";

    const Entry* known = nullptr;
    if (mode == "detect") {
        for (const Entry& c : catalogue) {
            if (mk::same_card(driver_name, c.name)) {
                known = &c;
            }
        }
    }
    if (known != nullptr) {
        header += std::string("// Device 0 is the ") + known->name + ": gpu_catalogue.hpp's numbers must be the driver's.\n";
        header += check(known->type, "sms", "==", static_cast<std::uint64_t>(p.multiProcessorCount), "is not");
        header += check(known->type, "cuda_arch", "==", arch, "is not");
        header += check(known->type, "shared_per_sm", "==", shared_per_sm, "is not");
        header += check(known->type, "shared_reserved_per_block", "==", reserved, "is not");
        // A card's total memory varies a little with the driver: only a claim of more is wrong.
        header += check(known->type, "device_memory", "<=", p.totalGlobalMem, "claims more than");
    } else {
        header += "// Device 0 of the machine that configured this build.\nstruct DetectedGpu {\n";
        header += "    static constexpr const char*   name                      = \"" + driver_name + "\";\n";
        header += "    static constexpr unsigned      sms                       = " + std::to_string(p.multiProcessorCount) + ";\n";
        header += "    static constexpr unsigned      cuda_arch                 = " + std::to_string(arch) + ";\n";
        header += "    static constexpr std::uint64_t device_memory             = " + std::to_string(p.totalGlobalMem) + ";\n";
        header += "    static constexpr unsigned      shared_per_sm             = " + std::to_string(shared_per_sm) + ";\n";
        header += "    static constexpr unsigned      shared_reserved_per_block = " + std::to_string(reserved) + ";\n";
        header += "    // Unmeasured: the RTX 4070 Ti SUPER's. Measure it on this card before trusting it.\n";
        header += "    static constexpr unsigned      blocks_per_sm             = " + std::to_string(unmeasured_blocks_per_sm) + ";\n";
        header += "};\nstatic_assert(GpuSpec<DetectedGpu>);\n";
    }
    header += "}\n";
    if (!write_if_changed(out, header)) {
        return fail("cannot write " + out);
    }
    std::printf("%s %u %s, %s\n", known != nullptr ? known->type : "DetectedGpu", arch,
                facts.c_str(), known != nullptr ? "the catalogue's type" : "a generated type");
    return 0;
}
